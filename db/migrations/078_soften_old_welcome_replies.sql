-- 10/22 대표님: 예전 환영 답글 틀("반가워요! 👋", "한 분 더 오셨어요 ⚡", 다른 사람 @소개)이 AI 같다 → 지우지 말고 조금씩만 고친다.
-- 운영 닉네임이 단 답글만. 다른 사람을 부르던 @소개는 빼고, 그 사람 결과·팀에만 짧게 반응하는 말로 줄인다.
UPDATE comments SET body = CASE
    WHEN body ~ '^(.+?)님 반가워요! 👋 위에 다른 분들 결과도 구경해 보세요\. 같은 타입 있을지도요\.$'
      THEN regexp_replace(body, '^(.+?)님 반가워요! 👋 위에 다른 분들 결과도 구경해 보세요\. 같은 타입 있을지도요\.$', '\1님 결과 잘 봤어요')
    WHEN body ~ '^(.+?)님 반가워요! 👋 @.+?님도 같은 (.+?)예요\. 서로 어떤 점이 비슷한지 이야기 나눠 보실래요\?$'
      THEN regexp_replace(body, '^(.+?)님 반가워요! 👋 @.+?님도 같은 (.+?)예요\. 서로 어떤 점이 비슷한지 이야기 나눠 보실래요\?$', '\1님 \2 나왔네요')
    WHEN body ~ '^(.+?)님 반가워요! 👋 @.+?님도 (.+?) 팬이에요\. 두 분 올 시즌 제일 기억에 남는 경기 하나씩 나눠 보실래요\?$'
      THEN regexp_replace(body, '^(.+?)님 반가워요! 👋 @.+?님도 (.+?) 팬이에요\. 두 분 올 시즌 제일 기억에 남는 경기 하나씩 나눠 보실래요\?$', '\2 팬이시구나')
    WHEN body ~ '^@.+?님, (.+?) 팬 한 분 더 오셨어요 ⚡ (.+?)님은 주로 직관이세요, 중계세요\?$'
      THEN regexp_replace(body, '^@.+?님, (.+?) 팬 한 분 더 오셨어요 ⚡ (.+?)님은 주로 직관이세요, 중계세요\?$', '\1 팬이시네요. 주로 직관 가세요?')
    WHEN body ~ '^오 (.+?) 또 나왔다 ㅎㅎ @.+?님이랑 같은 타입이에요\. .+?님은 결과 맞는 것 같아요\?$'
      THEN regexp_replace(body, '^오 (.+?) 또 나왔다 ㅎㅎ @.+?님이랑 같은 타입이에요\. .+?님은 결과 맞는 것 같아요\?$', '오 \1 나왔다 ㅎㅎ')
    WHEN body ~ '^(.+?)님이랑 @.+?님 둘 다 (.+?)! 두 분 공통점 찾아보세요 👀$'
      THEN regexp_replace(body, '^(.+?)님이랑 @.+?님 둘 다 (.+?)! 두 분 공통점 찾아보세요 👀$', '\2 나왔네요')
    WHEN body ~ '^(.+?)님 (.+?)! 위에 @.+?님도 같은 팀이에요\. 요즘 제일 좋아하는 선수 한 명씩 꼽아 보면 재밌겠네요\.$'
      THEN regexp_replace(body, '^(.+?)님 (.+?)! 위에 @.+?님도 같은 팀이에요\. 요즘 제일 좋아하는 선수 한 명씩 꼽아 보면 재밌겠네요\.$', '\2 팬이시네요')
    ELSE body END
 WHERE nickname IN ('노방장', '돈키호테', '덕후1호')
   AND parent_id IS NOT NULL
   AND (body LIKE '%반가워요! 👋%' OR body LIKE '%한 분 더 오셨어요 ⚡%' OR body LIKE '%또 나왔다 ㅎㅎ @%'
     OR body LIKE '%공통점 찾아보세요 👀%' OR body LIKE '%꼽아 보면 재밌겠네요.%');
