export function roomPollTopic(slug: string, day: string): [string, string] | null {
  const set = ROOM_POLLS[slug];
  if (!set) return null;
  const n = Math.max(0, Math.round((Date.parse(`${day}T00:00:00Z`) - Date.parse(`${set.start}T00:00:00Z`)) / 86_400_000));
  return set.polls[n % set.polls.length]!;
}
