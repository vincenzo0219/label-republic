const dayIndex = (day: string) => Math.floor(Date.parse(`${day}T00:00:00Z`) / 86_400_000);
export const isTypeDay = (day: string) => new Date(`${day}T00:00:00Z`).getUTCDay() === 6;
/** 홀수 날은 정답 퀴즈 차례 (기본 목록에 있을 때만) */
export const isTriviaDay = (day: string) => dayIndex(day) % 2 === 1;

/** 🔥 연속 참여 배지 단계 (3·7·30일) */
export const streakTier = (n: number): 0 | 3 | 7 | 30 => (n >= 30 ? 30 : n >= 7 ? 7 : n >= 3 ? 3 : 0);

/** 운영자 줄이 없을 때 오늘의 퀴즈. ROOM_POLLS 가 있는 방은 그 방의 오늘 질문을 같은 카드(손맛·폭죽·카드 모음)로 (10/29 대표님 "누르고 싶은 장치 진행") */
export function builtinQuiz(slug: string, day: string): RoomQuiz | null {
  if (QUIZ_EXCLUDED.has(slug)) return null;
  if (isTypeDay(day)) return GENERIC_TYPE;
  const poll = ROOM_POLLS[slug] ? roomPollTopic(slug, day) : null;
  if (poll) return { kind: "pick", q: `${ROOM_POLLS[slug]!.emoji} 오늘의 질문, 당신은?`, options: [poll[0], poll[1]] } as RoomQuiz;
  const i = dayIndex(day);
  const trivia = BUILTIN_TRIVIA[slug];
  if (isTriviaDay(day) && trivia?.length) return trivia[Math.floor(i / 2) % trivia.length]!;
  const list = BUILTIN_PICKS[slug] ?? GENERIC_PICKS;
  return list[i % list.length]!;
}

/** 유형 테스트 결과: 가장 많이 고른 유형 (같으면 먼저 나온 유형) */
export function scoreType(quiz: TypeQuiz, picks: number[]): string | null {
  if (picks.length !== quiz.questions.length) return null;
  const count = new Map<string, number>();
  for (let i = 0; i < picks.length; i++) {
    const o = quiz.questions[i]!.options[picks[i]!];
    if (!o) return null;
    count.set(o.type, (count.get(o.type) ?? 0) + 1);
  }
  let best: string | null = null;
  for (const [t, n] of count) if (best === null || n > count.get(best)!) best = t;
  return best;
}

/** 0~100 반올림 비율 (전체 0이면 0) */
export const pct = (n: number, total: number) => (total > 0 ? Math.round((n * 100) / total) : 0);

/** 운영자가 넣는 퀴즈 검사 (PUT /api/admin/room-quizzes). 문제 없으면 null */
export function quizProblem(q: unknown): string | null {
  const x = q as RoomQuiz;
  if (!x || (x.kind !== "pick" && x.kind !== "type" && x.kind !== "trivia")) return "kind 는 pick, type, trivia";
  if (x.kind === "pick" || x.kind === "trivia") {
    if (typeof x.q !== "string" || !x.q.trim() || x.q.length > 80) return "q 는 1~80자";
    if (!Array.isArray(x.options) || x.options.length < 2 || x.options.length > 4) return "options 는 2~4개";
    if (x.options.some((o) => typeof o !== "string" || !o.trim() || o.length > 30)) return "option 은 1~30자";
    if (x.kind === "trivia") {
      if (!Number.isInteger(x.answer) || x.answer < 0 || x.answer >= x.options.length) return "answer 는 정답 보기 번호";
      if (typeof x.why !== "string" || !x.why.trim() || x.why.length > 120) return "why 는 1~120자";
      if (typeof x.source !== "string" || !/^https:\/\/\S+$/.test(x.source)) return "source 는 https 출처 주소";
    }
    return null;
  }
  if (typeof x.title !== "string" || !x.title.trim() || x.title.length > 60) return "title 은 1~60자";
  if (!Array.isArray(x.questions) || x.questions.length < 3 || x.questions.length > 4) return "questions 는 3~4개";
  if (!x.results || typeof x.results !== "object") return "results 가 필요해요";
  for (const qq of x.questions) {
    if (typeof qq.q !== "string" || !qq.q.trim() || qq.q.length > 80) return "질문은 1~80자";
    if (!Array.isArray(qq.options) || qq.options.length < 2 || qq.options.length > 4) return "질문마다 보기 2~4개";
    for (const o of qq.options) {
      if (typeof o.label !== "string" || !o.label.trim() || o.label.length > 30) return "보기는 1~30자";
      if (!x.results[o.type]) return `results 에 없는 유형: ${o.type}`;
    }
  }
  for (const r of Object.values(x.results)) if (typeof r?.name !== "string" || typeof r?.line !== "string") return "results 는 {name, line}";
  return null;
}
