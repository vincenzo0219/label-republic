export type StationHit = { sido: string; sigungu: string };

const MAP = new Map<string, StationHit>();
for (const line of TABLE.trim().split("\n")) {
  const [region, names] = line.split(":");
  const [sido, sigungu = ""] = region!.trim().split(" ");
  for (const n of names!.split(",")) {
    const name = n.trim();
    // 같은 이름이 두 곳에 있으면(동천·중동·논현·시청…) 먼저 나온 곳 (서울·경기가 앞)
    if (name && !MAP.has(name)) MAP.set(name, { sido: sido!, sigungu });
  }
}

/** 역 이름(‘역’ 없이) → 지역. 모르면 null */
export const stationRegion = (name: string): StationHit | null => MAP.get(name.replace(/역$/, "")) ?? null;
export const STATION_COUNT = MAP.size;
