import { describe, expect, it } from "vitest";
import { parseWon } from "@/lib/won";

describe("💳 넣어둬 가격 자유 입력", () => {
  it.each([
    ["10000", 10_000], ["10,000", 10_000], ["1만", 10_000], ["1만원", 10_000], ["만원", 10_000],
    ["3만5천", 35_000], ["3만 5천원", 35_000], ["35000원", 35_000], ["1.5만", 15_000], ["12만9천", 129_000],
    ["120만", 1_200_000], ["1백만원", 1_000_000], ["4,444", 4444], ["2억", 200_000_000], ["5천원", 5000],
  ])("%s → %i", (s, n) => expect(parseWon(s)).toBe(n));
  it.each(["", "원", "abc", "1만abc", "만만", "1만2억"])("%s → 못 읽음", (s) => expect(parseWon(s)).toBeNull());
});
